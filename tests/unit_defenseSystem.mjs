import assert from 'node:assert/strict';
import { DefenseSystem } from '../src/game/defenseSystem.js';
let checks = 0;
const eq = (a, b, m) => { checks++; assert.equal(a, b, m); };
const ok = (v, m) => { checks++; assert.ok(v, m); };
const defense = new DefenseSystem();
defense.activate(1, 'guard', 1000, 1500);
let result = defense.resolveIncomingAttack(1, 0, 40, 1200);
eq(result.applied, 10, 'guard absorbs 75 percent');
ok(result.blocked, 'guard marks attack blocked');
defense.activate(1, 'counter', 2000, 1800);
result = defense.resolveIncomingAttack(1, 0, 40, 2300);
eq(result.applied, 0, 'counter prevents incoming damage');
eq(result.counterDamage, 16, 'counter reflects 40 percent');
result = defense.resolveIncomingAttack(1, 0, 40, 2400);
eq(result.applied, 40, 'counter is consumed by one hit');
defense.activate(0, 'guard', 3000, 1500);
const snap = defense.getSnapshot(3200);
const replica = new DefenseSystem();
replica.applySnapshot(snap, 5000);
eq(replica.getSnapshot(5000)[0].guardRemaining, 1300, 'defense state sync preserves remaining duration');
replica.reset();
eq(replica.getSnapshot(5000)[0].guardRemaining, 0, 'reset clears defense windows');
console.log(`Phase 7 defense system: ${checks}/${checks} passed`);
