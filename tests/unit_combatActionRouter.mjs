import assert from 'node:assert/strict';
import { CombatActionRouter, COMBAT_ACTIONS } from '../src/game/combatActionRouter.js';
let checks = 0;
const ok = (v, m) => { checks++; assert.ok(v, m); };
const eq = (a, b, m) => { checks++; assert.equal(a, b, m); };
const completed = [];
const router = new CombatActionRouter({ onEvent: (e) => { if (e.type === 'complete') completed.push(e.action); } });
const feed = (sequence, start = 1000) => sequence.forEach((sign, i) => router.handleSignEvent({ sign, timestamp: start + i * 220 }));
feed(['SNAKE', 'TIGER', 'HORSE', 'RAM']);
eq(completed.at(-1).id, 'fire-burst', 'existing fire sequence preserved');
feed(['TIGER', 'RAM', 'SNAKE'], 3000);
eq(completed.at(-1).id, 'lightning-arc', 'existing lightning sequence preserved');
feed(['HORSE', 'SNAKE', 'TIGER'], 5000);
eq(completed.at(-1).id, 'wind-blade', 'existing wind sequence preserved');
feed(['RAM', 'TIGER'], 7000);
eq(completed.at(-1).id, 'guard', 'guard sequence routed');
feed(['TIGER', 'SNAKE', 'RAM'], 9000);
eq(completed.at(-1).id, 'counter', 'counter sequence routed');
ok(COMBAT_ACTIONS.filter(a => a.kind === 'attack').length === 3, 'three attack combinations available');
ok(COMBAT_ACTIONS.filter(a => a.kind === 'defense').length === 2, 'two defense combinations available');
const router2 = new CombatActionRouter();
router2.handleSignEvent({ sign: 'TIGER', timestamp: 10 });
router2.handleSignEvent({ sign: 'BOAR', timestamp: 20 });
eq(router2.getState().buffer.length, 0, 'unsupported sign cannot progress a combo');
console.log(`Phase 7 action router: ${checks}/${checks} passed`);
