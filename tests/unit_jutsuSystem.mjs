import assert from "node:assert/strict";
import { PlayerState } from "../src/game/playerState.js";
import { CombatEngine } from "../src/game/combatEngine.js";
import { JUTSUS, findJutsu, createJutsuSystem } from "../src/game/jutsuSystem.js";
import { createSequenceRecognizer } from "../src/game/sequenceRecognizer.js";
import { createJutsuBridge } from "../src/game/jutsuBridge.js";
import { Effects } from "../src/render/effects.js";
let checks=0; const ok=(v,m)=>{checks++;assert.ok(v,m)}; const eq=(a,b,m)=>{checks++;assert.equal(a,b,m)};
ok(findJutsu(["SNAKE","TIGER","HORSE","RAM"])?.id==="fire-burst","fire maps");
ok(findJutsu(["DRAGON","BIRD","RAT"])===null,"unsupported signs do not map");
ok(findJutsu(["HORSE","SNAKE","TIGER"])?.damage===34,"guardian summon damage");
eq(JUTSUS.find(j=>j.id==="lightning-arc").damage,30,"lightning damage");
ok(findJutsu(["TIGER","RAM","SNAKE"])?.id==="lightning-arc","lightning sequence maps");

const directPlayers=[new PlayerState(100),new PlayerState(100)];
const directCombat=new CombatEngine({players:directPlayers});
const directChars=[{x:10,feetY:20,attack(){this.attacked=true;}},{x:90,feetY:20,flashHit(){}}];
const directEffects=new Effects();
const directSystem=createJutsuSystem({combat:directCombat,effects:directEffects,characters:directChars});
const ready={type:"JUTSU_READY",eventId:77,sequence:JUTSUS[0].sequence};
const result=directSystem.execute(ready,0);
eq(result.type,"executed","Jutsu executes");
eq(result.jutsu.damage,25,"fire damage correct");
eq(directEffects.items.length,1,"effect launched");
eq(directSystem.execute({type:"JUTSU_READY",eventId:78,sequence:["DRAGON","BIRD","RAT"]},0).reason,"unknown-sequence","unsupported signs cannot launch attacks");
eq(directSystem.execute(ready,0).reason,"duplicate","same ready event consumed once");

const players=[new PlayerState(100),new PlayerState(100)];
const combat=new CombatEngine({players});
const characters=[{x:10,feetY:20,attack(){this.attacked=true;}},{x:90,feetY:20,flashHit(){}}];
const effects=new Effects();
const system=createJutsuSystem({combat,effects,characters});
const sequence=createSequenceRecognizer(); sequence.setSequence(JUTSUS[0].sequence);
const bridge=createJutsuBridge(); let readyEvent, completionEvent;
bridge.subscribe(e=>{readyEvent=e; system.execute(e,0);});
sequence.subscribe(e=>{if(e.type==="complete") {completionEvent=e; bridge.handleSequenceEvent(e);}});
JUTSUS[0].sequence.forEach((sign,i)=>sequence.handleSignEvent({sign,timestamp:i+1}));
ok(readyEvent?.type==="JUTSU_READY","sequence completion emits bridge event");
eq(effects.items.length,1,"integration launches visual attack");
eq(players[1].hp,100,"damage waits for projectile impact");
eq(bridge.handleSequenceEvent(completionEvent).reason,"duplicate-completion","same completion event cannot emit twice");
effects.update(1,e=>combat.damagePlayer(1,JUTSUS.find(j=>j.effectType===e.type).damage,e.type));
eq(players[1].hp,75,"impact applies mapped damage");
effects.update(1,e=>combat.damagePlayer(1,25,e.type));
eq(players[1].hp,75,"one projectile applies damage only once");
console.log(`Phase 6 Jutsu/integration: ${checks}/${checks} passed`);
